def jp_fix(text: str) -> str:
    """CN 混入を日本語標準字体へ置換し、地図外の JIS 圏外文字は除去する。"""
    out = []
    for ch in text:
        if ch in CN2JP:
            out.append(CN2JP[ch])
        elif _non_jis(ch) and not ch.isascii() and ch not in JP_SHARED and ch not in "「」『』・、。ー":
            continue  # 変換先のない JIS 圏外文字は落ちる
        else:
            out.append(ch)
    return "".join(out)


