def _non_jis(ch: str) -> bool:
    o = ord(ch)
    if o < 0x2E80:
        return False
    if ch in JP_SHARED or ch in "「」『』・、。":
        return False
    try:
        return ch.encode("cp932").decode("cp932") != ch
    except Exception:
        return True



